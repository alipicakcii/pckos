"""Generate PCKOS UI Mono, a monochrome 8x16 ASCII font.

Requires Pillow and DejaVu Sans Mono. The generated table is checked in, so
building PCKOS itself requires neither Pillow nor a host font installation.
Source typeface attribution/license: assets/fonts/LICENSE-DejaVu.txt.
"""
from pathlib import Path
import argparse

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', type=Path,
                        default=Path('/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf'))
    parser.add_argument('--output', type=Path,
                        default=ROOT / 'kernel/include/device/video/font8x16.hh')
    args = parser.parse_args()
    font = ImageFont.truetype(str(args.font), 13)
    lines = [
        '#ifndef FONT_8X16_HH', '#define FONT_8X16_HH', '',
        '#include <stdint.h>', '', 'namespace device', '{',
        '    // PCKOS UI Mono: real 8x16 glyphs, without vertical stretching.',
        '    // Generated by tools/mkfont.py from DejaVu Sans Mono 13px.',
        '    // Font copyright and license: assets/fonts/LICENSE-DejaVu.txt.',
        '    constexpr uint8_t font8x16[128][16] = {',
    ]
    for codepoint in range(128):
        glyph = Image.new('1', (8, 16), 0)
        if 32 <= codepoint < 127:
            ImageDraw.Draw(glyph).text((0, 0), chr(codepoint), font=font, fill=1)
        rows = [sum((1 << (7 - x)) if glyph.getpixel((x, y)) else 0
                    for x in range(8)) for y in range(16)]
        row_text = ', '.join(f'0x{row:02X}' for row in rows)
        lines.append(f'        {{{row_text}}}, // ASCII {codepoint}')
    lines.extend(['    };', '}', '', '#endif', ''])
    args.output.write_text('\n'.join(lines), encoding='utf-8')


if __name__ == '__main__':
    main()
